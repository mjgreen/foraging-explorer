options(shiny.useragg = FALSE, shiny.usecairo = FALSE)
app <- new.env(parent = globalenv())
source("app.R", local = app)
shiny::testServer(app$server, {
  session$setInputs(view = "both", runs = 20, seed = 17, run = 0, new_runs = 0)
  session$setInputs(run = 1)
  original <- results()
  stopifnot(original$n == 20, original$seed == 17)
  session$setInputs(view = "memory")
  stopifnot(identical(original, results()))
  session$setInputs(runs = 40)
  stopifnot(identical(original, results()))
  session$setInputs(run = 2)
  more <- results()
  selected <- more$data$trajectory %in% original$data$trajectory
  stopifnot(identical(original$data$tally, more$data$tally[selected]))
  session$setInputs(new_runs = 1)
  stopifnot(results()$seed == 18, !identical(more$data$tally, results()$data$tally))
  valid <- results()
  session$setInputs(runs = -1, run = 3)
  stopifnot(identical(valid, results()))
})
cat("Foraging server preserves results across view/settings changes and reruns deliberately\n")
